#!/usr/bin/env node
// Reads the v0 schema and emits a generated TS module the worker imports.
// This avoids JSON-import syntax differences across bundler versions.

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = join(
  here,
  "..",
  "..",
  "packages",
  "schema",
  "manifest.schema.v0.json",
);
const outPath = join(here, "..", "src", "generated", "schema-v0.ts");

const json = await readFile(schemaPath, "utf8");
const parsed = JSON.parse(json);
const text = [
  "// AUTO-GENERATED by site/scripts/embed-schema.mjs — do not edit by hand.",
  "// Re-run: cd site && node scripts/embed-schema.mjs",
  "",
  `export const SCHEMA_V0 = ${JSON.stringify(parsed, null, 2)} as const;`,
  "",
].join("\n");

await mkdir(dirname(outPath), { recursive: true });
await writeFile(outPath, text, "utf8");
console.error(`embed-schema: wrote ${outPath} (${json.length} bytes source)`);
